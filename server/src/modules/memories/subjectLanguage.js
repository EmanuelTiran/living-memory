function applyReplacements(
  text,
  replacements,
) {
  return replacements.reduce(
    (current, [source, target]) =>
      current.replaceAll(
        source,
        target,
      ),
    text,
  )
}

export function personalizeSubjectText(
  text,
  {
    subjectName = '',
    subjectGender = 'unspecified',
  } = {},
) {
  if (typeof text !== 'string') {
    return text
  }

  let personalizedText = text

  if (subjectGender === 'female') {
    personalizedText =
      applyReplacements(
        personalizedText,
        FEMININE_REPLACEMENTS,
      )
  }

  if (subjectName.trim()) {
    personalizedText =
      personalizedText.replaceAll(
        'האדם',
        subjectName.trim(),
      )
  }

  return personalizedText
}

export function personalizeBiographyQuestion(
  question,
  subject,
) {
  return {
    ...question,
    question: personalizeSubjectText(
      question.question,
      subject,
    ),
    options: question.options.map(
      (option) => ({
        ...option,
        label: personalizeSubjectText(
          option.label,
          subject,
        ),
      }),
    ),
  }
}
